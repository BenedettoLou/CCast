#import "clipboardMonitor.h"
#import <ImageIO/ImageIO.h>

#include <cstdint>

static const NSTimeInterval kPollInterval   = 0.5;
static const NSTimeInterval kPollTolerance  = 0.2;   // lets macOS coalesce wakeups
static const NSInteger      kThumbnailPixels = 64;   // 32pt row icon at 2x

// nspasteboard.org markers set by password managers and similar tools
static NSPasteboardType const kConcealedType     = @"org.nspasteboard.ConcealedType";
static NSPasteboardType const kTransientType     = @"org.nspasteboard.TransientType";
static NSPasteboardType const kAutoGeneratedType = @"org.nspasteboard.AutoGeneratedType";

@implementation ClipboardCapture
@end

@implementation ClipboardMonitor {
  void (^_handler)(ClipboardCapture *);
  NSTimer *_timer;
  NSInteger _lastChangeCount;
  dispatch_queue_t _imageQueue;
}

  - (instancetype) initWithHandler: (void (^)(ClipboardCapture *capture)) handler {
    self = [super init];
    if (self) {
      _handler = [handler copy];
      _lastChangeCount = -1;
      _imageQueue = dispatch_queue_create("ccast.clipboard.images", DISPATCH_QUEUE_SERIAL);
    }
    return self;
  }

  - (void) dealloc {
    [_timer invalidate];
  }

  - (void) start {
    if (_timer) return;
    __weak ClipboardMonitor *weakSelf = self;
    _timer = [NSTimer scheduledTimerWithTimeInterval:kPollInterval
                                             repeats:YES
                                               block:^(NSTimer *timer) {
      (void)timer;
      [weakSelf pollUserInitiated:NO];
    }];
    _timer.tolerance = kPollTolerance;
  }

  - (void) stop {
    [_timer invalidate];
    _timer = nil;
  }

  #pragma mark - Access

  - (BOOL) backgroundCaptureAllowed {
    if (@available(macOS 15.4, *)) {
      const NSPasteboardAccessBehavior behavior = NSPasteboard.generalPasteboard.accessBehavior;
      return behavior == NSPasteboardAccessBehaviorDefault ||
             behavior == NSPasteboardAccessBehaviorAlwaysAllow;
    }
    return YES;
  }

  - (BOOL) accessDenied {
    if (@available(macOS 15.4, *)) {
      return NSPasteboard.generalPasteboard.accessBehavior == NSPasteboardAccessBehaviorAlwaysDeny;
    }
    return NO;
  }

  #pragma mark - Reading

  - (void) pollUserInitiated: (BOOL) userInitiated {
    NSPasteboard *pb = NSPasteboard.generalPasteboard;
    const NSInteger changeCount = pb.changeCount;
    if (changeCount == _lastChangeCount) return;

    // reading the content may trigger the macOS paste alert: in the background
    // only when always allowed. The change stays pending for the next user action.
    if (self.accessDenied) return;
    if (!userInitiated && !self.backgroundCaptureAllowed) return;
    _lastChangeCount = changeCount;

    NSArray<NSPasteboardType> *types = pb.types;
    if ([types containsObject:kConcealedType] ||
        [types containsObject:kTransientType] ||
        [types containsObject:kAutoGeneratedType]) {
      return;
    }

    // Finder file copies also carry a TIFF icon: check them first
    if ([types containsObject:NSPasteboardTypeFileURL]) {
      [self captureFileFrom:pb];
      return;
    }

    NSData *png  = [pb dataForType:NSPasteboardTypePNG];
    NSData *tiff = png.length > 0 ? nil : [pb dataForType:NSPasteboardTypeTIFF];
    if (png.length > 0 || tiff.length > 0) {
      [self captureImageData:(png.length > 0 ? png : tiff)];
      return;
    }

    [self captureTextFrom:pb];
  }

  - (void) captureFileFrom: (NSPasteboard *) pb {
    NSArray<NSURL *> *urls = [pb readObjectsForClasses:@[[NSURL class]]
                                               options:@{NSPasteboardURLReadingFileURLsOnlyKey: @YES}];
    NSURL *url = urls.firstObject;
    if (!url.isFileURL || url.path.length == 0) return;

    ClipboardCapture *capture = [[ClipboardCapture alloc] init];
    capture.kind = ClipboardKind::File;
    capture.filePath = url.path;
    _handler(capture);
  }

  - (void) captureTextFrom: (NSPasteboard *) pb {
    NSString *text = [pb stringForType:NSPasteboardTypeString];
    if (text.length == 0) return;
    if ([text lengthOfBytesUsingEncoding:NSUTF8StringEncoding] > SearchClipboard::kMaxTextBytes) return;

    ClipboardCapture *capture = [[ClipboardCapture alloc] init];
    capture.kind = ClipboardKind::Text;
    capture.text = text;
    _handler(capture);
  }

  // decoding, PNG conversion, hashing and thumbnail happen off the main thread
  - (void) captureImageData: (NSData *) data {
    void (^handler)(ClipboardCapture *) = _handler;
    dispatch_async(_imageQueue, ^{
      ClipboardCapture *capture = [ClipboardMonitor imageCaptureFromData:data];
      if (!capture) return;
      dispatch_async(dispatch_get_main_queue(), ^{ handler(capture); });
    });
  }

  // thread safe: ImageIO only (no AppKit drawing)
  + (ClipboardCapture *) imageCaptureFromData: (NSData *) data {
    CGImageSourceRef source = CGImageSourceCreateWithData((__bridge CFDataRef)data, NULL);
    if (!source) return nil;
    if (CGImageSourceGetCount(source) == 0) { CFRelease(source); return nil; }

    NSDictionary *props = CFBridgingRelease(CGImageSourceCopyPropertiesAtIndex(source, 0, NULL));
    const long width  = [props[(__bridge NSString *)kCGImagePropertyPixelWidth] longValue];
    const long height = [props[(__bridge NSString *)kCGImagePropertyPixelHeight] longValue];

    // store PNG (compact); keep the original only if the conversion fails
    NSData *stored = data;
    NSPasteboardType storedType = NSPasteboardTypeTIFF;
    CFStringRef sourceType = CGImageSourceGetType(source);
    if (sourceType && CFEqual(sourceType, CFSTR("public.png"))) {
      storedType = NSPasteboardTypePNG;
    } else if (NSData *png = [self pngFromSource:source]) {
      stored = png;
      storedType = NSPasteboardTypePNG;
    }

    NSDictionary *thumbOptions = @{
      (__bridge NSString *)kCGImageSourceCreateThumbnailFromImageAlways: @YES,
      (__bridge NSString *)kCGImageSourceCreateThumbnailWithTransform: @YES,
      (__bridge NSString *)kCGImageSourceThumbnailMaxPixelSize: @(kThumbnailPixels),
    };
    CGImageRef thumbRef = CGImageSourceCreateThumbnailAtIndex(source, 0,
                                                              (__bridge CFDictionaryRef)thumbOptions);
    CFRelease(source);
    NSImage *thumbnail = nil;
    if (thumbRef) {
      thumbnail = [[NSImage alloc] initWithCGImage:thumbRef size:NSZeroSize];
      CGImageRelease(thumbRef);
    }

    // 64-bit FNV-1a of the stored bytes: the same image copied twice is one entry
    uint64_t hash = 14695981039346656037ULL;
    const auto *bytes = static_cast<const uint8_t *>(stored.bytes);
    for (NSUInteger i = 0; i < stored.length; ++i) {
      hash ^= bytes[i];
      hash *= 1099511628211ULL;
    }

    ClipboardCapture *capture = [[ClipboardCapture alloc] init];
    capture.kind = ClipboardKind::Image;
    capture.imageID = [NSString stringWithFormat:@"%016llx", static_cast<unsigned long long>(hash)];
    capture.imageData = stored;
    capture.imageType = storedType;
    capture.thumbnail = thumbnail;
    capture.subtitle = [NSString stringWithFormat:@"Image · %ld × %ld · %lu KB",
                        width, height,
                        static_cast<unsigned long>(MAX(stored.length / 1024, (NSUInteger)1))];
    return capture;
  }

  + (NSData *) pngFromSource: (CGImageSourceRef) source {
    CGImageRef image = CGImageSourceCreateImageAtIndex(source, 0, NULL);
    if (!image) return nil;

    NSMutableData *out = [NSMutableData data];
    CGImageDestinationRef dest = CGImageDestinationCreateWithData((__bridge CFMutableDataRef)out,
                                                                  CFSTR("public.png"), 1, NULL);
    BOOL ok = NO;
    if (dest) {
      CGImageDestinationAddImage(dest, image, NULL);
      ok = CGImageDestinationFinalize(dest);
      CFRelease(dest);
    }
    CGImageRelease(image);
    return ok ? out : nil;
  }

  #pragma mark - Writing

  - (void) writeObject: (id<NSPasteboardWriting>) object {
    NSPasteboard *pb = NSPasteboard.generalPasteboard;
    [pb clearContents];
    [pb writeObjects:@[object]];
    _lastChangeCount = pb.changeCount;   // our own write is not a new capture
  }

  - (void) writeText: (NSString *) text {
    NSPasteboardItem *item = [[NSPasteboardItem alloc] init];
    [item setString:text forType:NSPasteboardTypeString];
    [self writeObject:item];
  }

  - (void) writeFileURL: (NSURL *) url {
    [self writeObject:url];
  }

  - (void) writeImageData: (NSData *) data type: (NSPasteboardType) type {
    NSPasteboardItem *item = [[NSPasteboardItem alloc] init];
    [item setData:data forType:type];

    // older apps only read TIFF: add it next to the PNG (one-off, user action)
    if ([type isEqualToString:NSPasteboardTypePNG]) {
      NSData *tiff = [NSBitmapImageRep imageRepWithData:data].TIFFRepresentation;
      if (tiff) [item setData:tiff forType:NSPasteboardTypeTIFF];
    }
    [self writeObject:item];
  }

@end
